package chapter01basic.whileloop.var;

public class Main {
  public static void main(String[] args) {
    int i = 1;
    while (i <= 5) {
      System.out.println(i + " times executed.");
      i++;
    }
  }
}

// 1 times executed.
// 2 times executed.
// 3 times executed.
// 4 times executed.
// 5 times executed.